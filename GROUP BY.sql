-- youngest customers to oldest customers
SELECT *
FROM CUSTOMERS
ORDER BY AGE;
-- ARRANGE CUSTOMERS BY CITY IF TWO CUSTOMERS BELONG TO SAME CITY ARRANGE THEM BY AGE
SELECT *
FROM CUSTOMERS 
ORDER BY CITY ASC, AGE ASC;
-- SHOW LATEST ORDERS FIRST
SELECT *
FROM ORDERS
ORDER BY ORDER_DATE DESC;
-- SHOW LATEST 10 ORDERS
SELECT *
FROM ORDERS
ORDER BY ORDER_DATE DESC
LIMIT 10;
-- SHOW TOP 3 OLDEST CUSTOMERS FROM NOIDA
SELECT *
FROM CUSTOMERS
WHERE CITY='Noida'
ORDER BY AGE DESC
LIMIT 3;
-- TOP 10 OLDEST PLATINUM CUSTOMERS
SELECT * 
FROM CUSTOMERS
WHERE LOYALTY_TIER='Platinum'
order by signup_date desc
limit 10;
-- show customers from delhi, age greater than 25,arrange them oldest to youngest,return only 3 customers
SELECT *
FROM CUSTOMERS
WHERE CITY = 'Delhi'
and age>25
order by age desc
limit 3;
-- how many customers we have in each city
SELECT  CITY, COUNT(CUSTOMER_ID)
FROM CUSTOMERS
GROUP BY CITY;
-- SHOW AVG AGE OF CUSTOMERS IN EACH CITY
SELECT CITY, AVG(AGE)
FROM CUSTOMERS
GROUP BY CITY;
-- SHOW YONGEST CUSTOMERS IN EACH CITY
SELECT CITY, MIN(AGE)
FROM CUSTOMERS
GROUP BY CITY;
-- COUNT HOW MANY CUSTOMERS SIGNUP ON EACH SIGNUP DATE
SELECT SIGNUP_DATE, COUNT(*)
FROM CUSTOMERS
GROUP BY SIGNUP_DATE;
-- SHOW NUMBER OF ORDERS FOR EACH ORDER STATUS
SELECT ORDER_STATUS , COUNT(ORDER_ID)
FROM ORDERS
GROUP BY ORDER_STATUS;
-- SHOW HOW MANY ORDERS EACH CUSTOMER HAS PLACED
SELECT CUSTOMER_ID, COUNT(ORDER_ID) AS TOTAL_ORDERS
FROM ORDERS
GROUP BY CUSTOMER_ID
ORDER BY TOTAL_ORDERS DESC;
-- SHOW AVG CUSTOMER AGE FOR EVERY SIGNUP DATE
SELECT SIGNUP_DATE, AVG(AGE)
FROM CUSTOMERS
GROUP BY SIGNUP_DATE;
-- PREPARE REPORT SHOWING NUMBER OF CUSTOMERS,AVG AGE, YOUNGEST CUSTOMERS, OLDEST CUSTOMER BY CITY
SELECT CITY, COUNT(CUSTOMER_ID) AS NUMBER_OF_CUSTOMERS,
ROUND(AVG(AGE),2) AS AVG_AGE,
MIN(AGE) AS YOUNGEST_CUSTOMERS,
MAX(AGE) AS OLDEST_CUSTOMERS
FROM CUSTOMERS
GROUP BY CITY;
-- WHICH CITIES HAVE HIGHEST NUMBER OF CUSTOMERS
SELECT CITY, COUNT(CUSTOMER_ID) AS NUMBER_OF_CUSTOMERS
FROM CUSTOMERS
GROUP BY CITY
ORDER BY NUMBER_OF_CUSTOMERS DESC;
-- COUNT CUSTOMERS IN EACH CITY AND GENDER
SELECT CITY, GENDER ,COUNT(CUSTOMER_ID)
FROM CUSTOMERS
GROUP BY CITY, GENDER;
-- SHOW ONLY CITIES WHERE CUSTOMER COUNT IS GREATER THAN 3
SELECT CITY, COUNT(CUSTOMER_ID) AS TOTAL_CUSTOMERS
FROM CUSTOMERS
GROUP BY CITY
HAVING COUNT(CUSTOMER_ID)>3;
-- SHOW ORDER STATUS HAVING MORE THAN 3 ORDERS
SELECT ORDER_STATUS, COUNT(ORDER_ID)
FROM ORDERS
GROUP BY ORDER_STATUS
HAVING COUNT(ORDER_ID)>3;
-- SHOW CUSTOMERS WHO HAVE PLACED MORE THAN 1 ORDER
SELECT CUSTOMER_ID, COUNT(ORDER_ID)
FROM ORDERS
GROUP BY CUSTOMER_ID
HAVING COUNT(ORDER_ID)>1;
-- PREPARE A CITY REPORT SHOWING CITY, NUMBER OF CUSTOMERS BT ONLY INCLUDE CITIES WITH AT LEAST 2 CUSTOMERS
SELECT CITY, COUNT(CUSTOMER_ID)
FROM CUSTOMERS
GROUP BY CITY
HAVING COUNT(CUSTOMER_ID)>=2;
-- Show cities where Average age > 25 and Customer count > 2
SELECT CITY, ROUND(AVG(AGE),2) AS AVERAGE_AGE, COUNT(CUSTOMER_ID) AS CUSTOMER_COUNT
FROM CUSTOMERS
GROUP BY CITY
HAVING AVG(AGE)>25
AND COUNT(CUSTOMER_ID)>2;



