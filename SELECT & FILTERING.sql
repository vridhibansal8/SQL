-- HOW MANY TOTAL NUMBER OF CUSTOMERS
SELECT COUNT(CUSTOMER_ID)
FROM CUSTOMERS;
-- HOW MANY UNIQUE CITY DO WE CURRENTLY SERVE
SELECT COUNT(DISTINCT CITY)
FROM CUSTOMERS;
-- HOW MANY CUSTOMERS BELONG TO CITY DELHI
SELECT COUNT(*)
FROM CUSTOMERS
WHERE CITY ='Delhi';
-- HOW MANY ORDERS HAVE BEEN PLACED IN TOTAL
SELECT COUNT(ORDER_ID) 
FROM ORDERS;
-- TOTAL SALES WHERE ORDER STATUS IS DELIVERED
SELECT SUM(QUANTITY*UNIT_PRICE)
FROM ORDER_ITEMS
WHERE ITEM_STATUS='Delivered'
